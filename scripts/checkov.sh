#!/bin/bash

set -u

echo "========================================"
echo "Checkov IaC Security Scan"
echo "========================================"

REPORT_DIR="reports/checkov"

DOCKERFILE_REPORT="${REPORT_DIR}/checkov-dockerfile-report.txt"
DOCKERFILE_JSON="${REPORT_DIR}/checkov-dockerfile-report.json"
DOCKERFILE_HTML="${REPORT_DIR}/checkov-dockerfile-report.html"

HELM_REPORT="${REPORT_DIR}/checkov-helm-report.txt"
HELM_JSON="${REPORT_DIR}/checkov-helm-report.json"
HELM_HTML="${REPORT_DIR}/checkov-helm-report.html"

mkdir -p "${REPORT_DIR}"

DOCKERFILE_STATUS=0
HELM_STATUS=0

generate_html_report() {

    local json_file="$1"
    local html_file="$2"
    local title="$3"

    if [ ! -f "${json_file}" ]; then
        echo "JSON report not found: ${json_file}"
        return 1
    fi

    python3 - "${json_file}" "${html_file}" "${title}" <<'PY'
import json
import html
import sys
from pathlib import Path

json_file = Path(sys.argv[1])
html_file = Path(sys.argv[2])
title = sys.argv[3]

try:
    data = json.loads(json_file.read_text())
except Exception as exc:
    print(f"Unable to parse Checkov JSON report: {exc}")
    sys.exit(1)

summary = data.get("summary", {})

passed = summary.get("passed", 0)
failed = summary.get("failed", 0)
skipped = summary.get("skipped", 0)

results = data.get("results", {})

failed_checks = results.get("failed_checks", [])
passed_checks = results.get("passed_checks", [])

rows = []

for item in failed_checks:
    rows.append({
        "status": "FAILED",
        "check_id": item.get("check_id", ""),
        "check_name": item.get("check_name", ""),
        "resource": item.get("resource", ""),
        "file_path": item.get("file_path", ""),
        "file_line_range": item.get("file_line_range", ""),
    })

for item in passed_checks:
    rows.append({
        "status": "PASSED",
        "check_id": item.get("check_id", ""),
        "check_name": item.get("check_name", ""),
        "resource": item.get("resource", ""),
        "file_path": item.get("file_path", ""),
        "file_line_range": item.get("file_line_range", ""),
    })

row_html = []

for row in rows:
    status_class = "failed" if row["status"] == "FAILED" else "passed"

    row_html.append(
        f"""
        <tr>
            <td class="{status_class}">{html.escape(str(row["status"]))}</td>
            <td>{html.escape(str(row["check_id"]))}</td>
            <td>{html.escape(str(row["check_name"]))}</td>
            <td>{html.escape(str(row["resource"]))}</td>
            <td>{html.escape(str(row["file_path"]))}</td>
            <td>{html.escape(str(row["file_line_range"]))}</td>
        </tr>
        """
    )

document = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>{html.escape(title)}</title>

<style>
body {{
    font-family: Arial, sans-serif;
    margin: 30px;
    background: #f5f5f5;
    color: #222;
}}

h1 {{
    margin-bottom: 5px;
}}

.subtitle {{
    color: #666;
    margin-bottom: 25px;
}}

.summary {{
    display: flex;
    gap: 15px;
    margin-bottom: 25px;
}}

.card {{
    background: white;
    padding: 18px;
    border-radius: 8px;
    min-width: 140px;
    box-shadow: 0 1px 4px rgba(0,0,0,0.12);
}}

.card .value {{
    font-size: 28px;
    font-weight: bold;
}}

table {{
    width: 100%;
    border-collapse: collapse;
    background: white;
}}

th, td {{
    border: 1px solid #ddd;
    padding: 10px;
    text-align: left;
    vertical-align: top;
}}

th {{
    background: #eeeeee;
}}

.failed {{
    color: #b00020;
    font-weight: bold;
}}

.passed {{
    color: #1b7f3a;
    font-weight: bold;
}}

.footer {{
    margin-top: 20px;
    color: #666;
    font-size: 13px;
}}
</style>
</head>

<body>

<h1>{html.escape(title)}</h1>

<div class="subtitle">
Generated by Checkov in Jenkins
</div>

<div class="summary">

<div class="card">
    <div>Passed</div>
    <div class="value">{passed}</div>
</div>

<div class="card">
    <div>Failed</div>
    <div class="value">{failed}</div>
</div>

<div class="card">
    <div>Skipped</div>
    <div class="value">{skipped}</div>
</div>

</div>

<table>
<thead>
<tr>
    <th>Status</th>
    <th>Check ID</th>
    <th>Check</th>
    <th>Resource</th>
    <th>File</th>
    <th>Line</th>
</tr>
</thead>

<tbody>
{''.join(row_html)}
</tbody>

</table>

<div class="footer">
Checkov report generated automatically by the DevSecOps Jenkins pipeline.
</div>

</body>
</html>
"""

html_file.write_text(document, encoding="utf-8")

print(f"HTML report generated: {html_file}")
PY
}

echo ""
echo "========================================"
echo "Checkov Dockerfile Scan"
echo "========================================"

if [ ! -f "Dockerfile" ]; then
    echo "Dockerfile not found."
    exit 1
fi

echo "Dockerfile found."

set +e

checkov \
    -f Dockerfile \
    --framework dockerfile \
    --output cli \
    > "${DOCKERFILE_REPORT}"

DOCKERFILE_STATUS=$?

checkov \
    -f Dockerfile \
    --framework dockerfile \
    --output json \
    > "${DOCKERFILE_JSON}"

DOCKERFILE_JSON_STATUS=$?

set -e

if [ "${DOCKERFILE_JSON_STATUS}" -ne 0 ] && [ "${DOCKERFILE_STATUS}" -eq 0 ]; then
    DOCKERFILE_STATUS=${DOCKERFILE_JSON_STATUS}
fi

generate_html_report \
    "${DOCKERFILE_JSON}" \
    "${DOCKERFILE_HTML}" \
    "Checkov Dockerfile Report"

echo ""
echo "Dockerfile report : ${DOCKERFILE_REPORT}"
echo "Dockerfile JSON   : ${DOCKERFILE_JSON}"
echo "Dockerfile HTML   : ${DOCKERFILE_HTML}"
echo "Dockerfile status : ${DOCKERFILE_STATUS}"

echo ""
echo "========================================"
echo "Checkov Helm Chart Scan"
echo "========================================"

CHART_PATH="../kubernetes/charts/application"

if [ ! -d "${CHART_PATH}" ]; then
    echo "Helm Chart directory not found: ${CHART_PATH}"
    exit 1
fi

if [ ! -f "${CHART_PATH}/Chart.yaml" ]; then
    echo "Chart.yaml not found: ${CHART_PATH}/Chart.yaml"
    exit 1
fi

echo "Helm Chart found: ${CHART_PATH}"

set +e

checkov \
    -d "${CHART_PATH}" \
    --framework helm \
    --output cli \
    > "${HELM_REPORT}"

HELM_STATUS=$?

checkov \
    -d "${CHART_PATH}" \
    --framework helm \
    --output json \
    > "${HELM_JSON}"

HELM_JSON_STATUS=$?

set -e

if [ "${HELM_JSON_STATUS}" -ne 0 ] && [ "${HELM_STATUS}" -eq 0 ]; then
    HELM_STATUS=${HELM_JSON_STATUS}
fi

generate_html_report \
    "${HELM_JSON}" \
    "${HELM_HTML}" \
    "Checkov Helm Chart Report"

echo ""
echo "Helm report       : ${HELM_REPORT}"
echo "Helm JSON         : ${HELM_JSON}"
echo "Helm HTML         : ${HELM_HTML}"
echo "Helm status       : ${HELM_STATUS}"

echo ""
echo "========================================"
echo "Checkov Summary"
echo "========================================"

if [ "${DOCKERFILE_STATUS}" -eq 0 ]; then
    echo "Dockerfile scan : PASSED"
else
    echo "Dockerfile scan : FAILED"
fi

if [ "${HELM_STATUS}" -eq 0 ]; then
    echo "Helm scan       : PASSED"
else
    echo "Helm scan       : FAILED"
fi

echo ""
echo "Reports:"
echo "  ${DOCKERFILE_REPORT}"
echo "  ${DOCKERFILE_JSON}"
echo "  ${DOCKERFILE_HTML}"
echo "  ${HELM_REPORT}"
echo "  ${HELM_JSON}"
echo "  ${HELM_HTML}"

echo ""
echo "========================================"

if [ "${DOCKERFILE_STATUS}" -ne 0 ] || [ "${HELM_STATUS}" -ne 0 ]; then
    echo "Checkov detected policy violations."
    echo "Pipeline will continue."
else
    echo "Checkov scan completed without policy violations."
fi

echo "========================================"

exit 0

echo "Checkov scan completed successfully."
echo "========================================"

exit 0
